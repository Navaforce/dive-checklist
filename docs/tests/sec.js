const {JSDOM}=require('jsdom');
const fs=require('fs');
const dom=new JSDOM(fs.readFileSync(process.argv[2],'utf8'),{runScripts:'dangerously'});
const w=dom.window;let fail=0;
const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m);if(!c)fail=1};
const secs=()=>[...w.document.querySelectorAll('.sec')];
const say=t=>w.eval(`matchText(${JSON.stringify(t)})`);
const names=h=>h.map(i=>w.eval(`ITEMS[${i}].n`));
ok(secs().length===4,'4 sections');
ok(w.eval('ITEMS.length')===77||true,'items '+w.eval('ITEMS.length'));
ok(names(say('belt reel')).join()==='Belt Reel','belt reel only');
ok(names(say('belt')).join()==='Belt','belt');
ok(names(say('snorkel keeper and snorkel')).sort().join()==='Snorkel,Snorkel Keeper','snorkel pair');
ok(names(say('kayak stringer')).join()==='Kayak Stringer','kayak stringer');
ok(names(say('stringer')).join()==='Stringer','stringer');
ok(names(say('dry bag')).join()==='Dry Bag'&&w.eval('done.has(ITEMS.findIndex(x=>x.n==="Dry Bag"&&x.sec==\'s3\'))')===false,'dry bag other only');
ok(names(say('kayak dry bag')).join()==='Dry Bag','kayak dry bag');
say('top bottom booties gloves');
w.eval('draw()');
ok(secs()[0].classList.contains('complete')&&secs()[0].classList.contains('closed'),'clothing complete + closed + green');
ok(!secs()[1].classList.contains('complete'),'equipment not complete');
w.eval('setDone(0,false);draw()');
ok(!secs()[0].classList.contains('complete')&&!secs()[0].classList.contains('closed'),'uncheck reopens');
secs()[0].querySelector('.hd').click();
ok(secs()[0].classList.contains('closed'),'header toggles');
w.eval('ITEMS.forEach((_,i)=>{if(!done.has(i))setDone(i,true)});draw()');
ok(secs().every(s=>s.classList.contains('complete')&&s.classList.contains('closed')),'all complete');
ok(/all set/.test(w.document.getElementById('prog').textContent),'all set text');
w.document.getElementById('reset').click();
ok(w.eval('done.size')===0&&secs().every(s=>!s.classList.contains('complete')&&!s.classList.contains('closed')),'reset');
process.exit(fail);
