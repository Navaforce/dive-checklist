const {JSDOM}=require('jsdom');
const html=require('fs').readFileSync(process.argv[2],'utf8');
let fail=0;const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m);if(!c)fail=1};
const mk=pre=>new JSDOM(html,{runScripts:'dangerously',url:'http://localhost/',beforeParse(w){if(pre)w.localStorage.setItem('gearcheck.edits.v1',JSON.stringify(pre))}}).window;
let w=mk();const D=()=>w.document;const secs=()=>[...D().querySelectorAll('.sec')];
ok(secs().every(s=>s.querySelector('.tog.on')),'all toggles green by default');
const n1=w.eval(`ITEMS.filter(i=>i.sec==='s1').length`),tot=w.eval('ITEMS.length');
secs()[1].querySelector('.tog').click();
ok(secs()[1].querySelector('.tog.off')&&secs()[1].classList.contains('skipped'),'toggle red');
ok(D().getElementById('prog').textContent.startsWith('0 of '+(tot-n1)),'progress excludes skipped');
ok(!/Dive Equipment: /.test(w.eval('missingText()'))||true,'x');
const name=w.eval('SECS[1].name');ok(!w.eval('missingText()').includes(name+':'),'missing skips section');
const first=w.eval(`ITEMS.find(i=>i.sec==='s1').n`);
ok(w.eval(`matchText(${JSON.stringify(first)})`).filter(i=>w.eval(`ITEMS[${i}].sec`)==='s1').length===0,'voice skips item in skipped section');
const sav=JSON.parse(w.localStorage.getItem('gearcheck.edits.v1'));
w=mk(sav);
ok(secs()[1].querySelector('.tog.off'),'persists after reload');
secs()[1].querySelector('.tog').click();
ok(D().getElementById('prog').textContent.startsWith('0 of '+tot)&&w.eval('missingText()').includes(name+':'),'back on restores');
process.exit(fail);
