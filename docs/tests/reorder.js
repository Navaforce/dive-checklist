const {JSDOM}=require('jsdom');
const html=require('fs').readFileSync(process.argv[2],'utf8');
let fail=0;const ok=(c,m)=>{console.log((c?'PASS ':'FAIL ')+m);if(!c)fail=1};
const mk=pre=>new JSDOM(html,{runScripts:'dangerously',url:'http://localhost/',beforeParse(w){if(pre)w.localStorage.setItem('gearcheck.edits.v1',JSON.stringify(pre))}}).window;
let w=mk();const D=()=>w.document;const secs=()=>[...D().querySelectorAll('.sec')];
const ids=sid=>w.eval(`ITEMS.filter(i=>i.sec==='${sid}').map(i=>i.id)`);
let a=ids('s1');
w.eval(`reorderItem(${JSON.stringify(a[0])},${JSON.stringify(a[2])},false)`);
let b=ids('s1');
ok(b.join()===[a[1],a[2],a[0],...a.slice(3)].join(),'move first after third');
w.eval(`reorderItem(${JSON.stringify(a[0])},${JSON.stringify(a[1])},true)`);
ok(ids('s1').join()===a.join(),'move back before second restores');
w.eval(`reorderItem(${JSON.stringify(a[3])},${JSON.stringify(a[0])},true)`);
const sav=JSON.parse(w.localStorage.getItem('gearcheck.edits.v1'));
w=mk(sav);
ok(ids('s1')[0]===a[3],'order persists after reload');
ok([...D().querySelectorAll('.sec[data-sec=s1] li[data-id]')][0].dataset.id===a[3],'DOM order matches');
const o=ids('s0')[0];
w.eval(`reorderItem(${JSON.stringify(a[3])},${JSON.stringify(o)},false)`);
ok(w.eval(`ITEMS.find(i=>i.id===${JSON.stringify(a[3])}).sec`)==='s0'&&ids('s0')[1]===a[3],'cross-section drop lands after target');
// toggle closes
w=mk();
secs()[2].querySelector('.tog').click();
ok(secs()[2].classList.contains('closed'),'red toggle closes section');
const s2=JSON.parse(w.localStorage.getItem('gearcheck.edits.v1'));
w=mk(s2);
ok(secs()[2].classList.contains('closed')&&secs()[2].querySelector('.tog.off'),'off section closed on load');
ok(!secs()[0].classList.contains('closed'),'other sections open');
secs()[2].querySelector('.tog').click();
ok(!secs()[2].classList.contains('closed'),'green toggle reopens');
secs()[2].querySelector('.tog').click();
D().getElementById('reset').click();
ok(secs()[2].classList.contains('closed'),'reset keeps off section closed');
process.exit(fail);
